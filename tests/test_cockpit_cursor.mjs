import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomBytes, createCipheriv } from 'node:crypto';
import { execFileSync, spawnSync } from 'node:child_process';
const dir = mkdtempSync(join(tmpdir(), 'cursor-collector-test-'));
const key = randomBytes(32);
writeFileSync(join(dir, 'secure-account-storage.key'), key.toString('base64'));
mkdirSync(join(dir, 'cursor_accounts'));
execFileSync('sqlite3', [join(dir, 'cursor_accounts.sqlite'), "CREATE TABLE summaries(account_id TEXT,email TEXT); INSERT INTO summaries VALUES('cursor_abcd','selected@example.test'),('cursor_beef','other@example.test');"]);
const nonce = randomBytes(12), cipher = createCipheriv('aes-256-gcm', key, nonce);
const raw = { email: 'selected@example.test', access_token: 'never-send-this-secret', cursor_usage_raw: {
  planUsage: { totalPercentUsed: 3.6 }, planInfo: { includedUsagePeriod: 'INCLUDED_USAGE_PERIOD_WEEKLY', includedUsageResetsAt: '1795443282490' } } };
const encrypted = Buffer.concat([cipher.update(JSON.stringify(raw)), cipher.final(), cipher.getAuthTag()]);
writeFileSync(join(dir, 'cursor_accounts/cursor_abcd.json'), JSON.stringify({ algorithm: 'AES-256-GCM', nonce: nonce.toString('base64'), ciphertext: encrypted.toString('base64') }));
const run = email => spawnSync(process.execPath, ['collector/push_cockpit_cursor.mjs', '--json'], { encoding: 'utf8', env: { ...process.env, COCKPIT_TOOLS_DATA_DIR: dir, CURSOR_ACCOUNT_EMAIL: email } });
const result = run('selected@example.test');
assert.equal(result.status, 0, result.stderr);
assert.deepEqual(JSON.parse(result.stdout), { source: 'cursor', accounts: [{ name: 'Cursor', summary: '已用 4%', plan: '周额度', included_usage: { used: 4, reset_at: 1795443282 } }] });
assert(!/selected@example|never-send|access_token/.test(result.stdout));
assert.notEqual(run('missing@example.test').status, 0);
assert.notEqual(run('').status, 0);
raw.cursor_usage_raw.planUsage.totalPercentUsed = null;
const invalidCipher = createCipheriv('aes-256-gcm', key, nonce);
const invalid = Buffer.concat([invalidCipher.update(JSON.stringify(raw)), invalidCipher.final(), invalidCipher.getAuthTag()]);
writeFileSync(join(dir, 'cursor_accounts/cursor_abcd.json'), JSON.stringify({ algorithm: 'AES-256-GCM', nonce: nonce.toString('base64'), ciphertext: invalid.toString('base64') }));
assert.notEqual(run('selected@example.test').status, 0);
console.log('Cursor collector: target selection, privacy, weekly reset and missing data checks passed');
